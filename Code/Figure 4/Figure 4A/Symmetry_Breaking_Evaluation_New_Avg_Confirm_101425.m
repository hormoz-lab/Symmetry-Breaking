%% Step 1: Input Files 
% Define the main directory containing all input files
parent_path     = '/n/data1/hms/sysbio/hormoz/users/suxuan';

% Specify paths to each individual OUTPUT file
OUTPUT6_csv     = fullfile(parent_path, 'OUTPUT6_asymmetry_cluster_weighted_summary_confirm_101425.csv');
OUTPUT7_csv     = fullfile(parent_path, 'OUTPUT7_asymmetry_cluster_weighted_summary_confirm_101425.csv');
OUTPUT8_csv     = fullfile(parent_path, 'OUTPUT8_asymmetry_cluster_weighted_summary_confirm_101425.csv');
OUTPUT9_csv     = fullfile(parent_path, 'OUTPUT9_asymmetry_cluster_weighted_summary_confirm_101425.csv');
OUTPUT10_csv    = fullfile(parent_path, 'OUTPUT10_asymmetry_cluster_weighted_summary_confirm_101425.csv');

% Read all CSV files as MATLAB tables while preserving original variable names
OUTPUT6_table   = readtable(OUTPUT6_csv,  'PreserveVariableNames', true);
OUTPUT7_table   = readtable(OUTPUT7_csv,  'PreserveVariableNames', true);
OUTPUT8_table   = readtable(OUTPUT8_csv,  'PreserveVariableNames', true);
OUTPUT9_table   = readtable(OUTPUT9_csv,  'PreserveVariableNames', true);
OUTPUT10_table  = readtable(OUTPUT10_csv, 'PreserveVariableNames', true);

% Shared key columns 
shared_col_name = {'alpha_ii', ...
                     'alpha_oo', ...
                     'alpha_io', ...
                     'betaL_ii', ...
                     'betaL_oo', ...
                     'betaL_io', ...
                     'betaL_oi', ...
                     'D1', ...
                     'dt'};

% Extract shared columns from one representative table (OUTPUT6)
shared_col      = OUTPUT6_table(:, shared_col_name);


%% Step 2: Compute averages
% Compute the average asymmetry across OUTPUT6–10
asymmetry_avg   = mean([OUTPUT6_table.asymmetry, ...
                        OUTPUT7_table.asymmetry, ...
                        OUTPUT8_table.asymmetry, ...
                        OUTPUT9_table.asymmetry, ...
                        OUTPUT10_table.asymmetry], 2);

% Compute the average loss across OUTPUT6–10
loss_avg        = mean([OUTPUT6_table.loss, ...
                        OUTPUT7_table.loss, ...
                        OUTPUT8_table.loss, ...
                        OUTPUT9_table.loss, ...
                        OUTPUT10_table.loss], 2);


%% Step 3: Build combined table
% Combine all shared parameters, asymmetry values, and loss values into one table
combine_table   = [shared_col, table( ...
                   asymmetry_avg, ...
                   OUTPUT6_table.asymmetry, ...
                   OUTPUT7_table.asymmetry, ...
                   OUTPUT8_table.asymmetry, ...
                   OUTPUT9_table.asymmetry, ...
                   OUTPUT10_table.asymmetry, ...
                   loss_avg, ...
                   OUTPUT6_table.loss, ...
                   OUTPUT7_table.loss, ...
                   OUTPUT8_table.loss, ...
                   OUTPUT9_table.loss, ...
                   OUTPUT10_table.loss)];

% Assign clear, descriptive names to each column for easy interpretation
combine_table.Properties.VariableNames = [shared_col_name, ...
                                         {'asymmetry_avg', ...
                                          'asymmetry_6', ...
                                          'asymmetry_7', ...
                                          'asymmetry_8', ... 
                                          'asymmetry_9', ... 
                                          'asymmetry_10', ...
                                          'loss_avg', ...
                                          'loss_6', ... 
                                          'loss_7', ... 
                                          'loss_8', ... 
                                          'loss_9', ... 
                                          'loss_10'}];


%% Step 4: Export the table
% Save the full combined table (unranked)
out_file = fullfile(parent_path, 'OUTPUT6_10_asymmetry_cluster_weighted_summary_confirm_101425_combined.csv');
writetable(combine_table, out_file);
fprintf('✅ Combined table saved: %s\n', out_file);

% Save the full combined table (ranked)
combine_table_ranked = sortrows(combine_table, 'asymmetry_avg', 'descend');
out_file_ranked = fullfile(parent_path, 'OUTPUT6_10_asymmetry_cluster_weighted_summary_confirm_101425_combined_ranked.csv');
writetable(combine_table_ranked, out_file_ranked);
fprintf('✅ Combined table ranked saved: %s\n', out_file_ranked);

